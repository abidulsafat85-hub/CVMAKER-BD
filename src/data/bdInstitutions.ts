export function searchInstitutions(
  query: string,
  list: InstitutionItem[]
): InstitutionItem[] {
  if (!query || !query.trim()) return [];
  const q = query.trim().toLowerCase();

  return list.filter((item) => {
    const nameLower = item.name.toLowerCase();
    const shortLower = item.short ? item.short.toLowerCase() : '';

    // Exact abbreviation match (e.g. 'dc', 'ndc', 'rumc')
    if (shortLower === q) return true;
    // Abbreviation prefix (e.g. 'd' matches 'dc', 'dcc')
    if (shortLower.startsWith(q)) return true;
    // Full name contains query
    if (nameLower.includes(q)) return true;

    // Word prefix matching (e.g. 'dhaka' matches 'Dhaka College')
    const words = nameLower.split(/[\s,.'\-()]+/);
    if (words.some((w) => w.startsWith(q))) return true;

    return false;
  }).slice(0, 25);
}
