// Helper to look up university courses by exact, abbreviation, or substring match
export function getUniversityCourses(institutionName: string): string[] {
  if (!institutionName || !institutionName.trim()) {
    return COMMON_UNIVERSITY_DEPARTMENTS;
  }
  const cleanInput = institutionName.trim().toLowerCase();

  // 1. Direct match with shortName or en
  const found = POPULAR_BD_UNIVERSITIES.find((u) => {
    const uEn = u.en.toLowerCase();
    const short = u.shortName?.toLowerCase();
    return (
      cleanInput === uEn ||
      (short && cleanInput === short) ||
      cleanInput.includes(uEn) ||
      uEn.includes(cleanInput) ||
      (short && cleanInput.includes(`(${short})`)) ||
      (short && cleanInput.includes(short))
    );
  });

  if (found && found.courses && found.courses.length > 0) {
    return found.courses;
  }

  // Fallback to common departments
  return COMMON_UNIVERSITY_DEPARTMENTS;
}
